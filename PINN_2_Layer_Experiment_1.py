def u_star(tx):
    t = tx[:, [0]]
    x = tx[:, [1]]
    return torch.exp(-t) * torch.sin(math.pi * x)

def forcing_f(tx):
    t = tx[:, [0]]
    x = tx[:, [1]]
    return (math.pi**2 - 1.0) * torch.exp(-t) * torch.sin(math.pi * x)

# Sampling
def sample_interior(n, gen=None):
    pts = torch.rand((n, 2), generator=gen, device=DEVICE, dtype=DTYPE)
    eps = 1e-6
    return pts.clamp(eps, 1 - eps)

def sample_boundary_initial(n, gen=None):
    n0 = n // 3
    n1 = n // 3
    n2 = n - n0 - n1

    x0 = torch.rand((n0, 1), generator=gen, device=DEVICE, dtype=DTYPE)
    t1 = torch.rand((n1, 1), generator=gen, device=DEVICE, dtype=DTYPE)
    t2 = torch.rand((n2, 1), generator=gen, device=DEVICE, dtype=DTYPE)

    pts0 = torch.cat([torch.zeros_like(x0), x0], dim=1)
    pts1 = torch.cat([t1, torch.zeros_like(t1)], dim=1)
    pts2 = torch.cat([t2, torch.ones_like(t2)], dim=1)
    return torch.cat([pts0, pts1, pts2], dim=0)

# Init
def init_theta_and_a(m, seed):
    g = torch.Generator(device="cpu")
    g.manual_seed(seed)

    theta = torch.randn((m, 3), generator=g, dtype=DTYPE)
    a = torch.randint(0, 2, (m, 1), generator=g, dtype=torch.int64)
    a = 2 * a.float() - 1.0

    theta = theta.to(DEVICE)
    a = a.to(DEVICE, dtype=DTYPE)
    return theta, a

# Two-layer PINN
def model_from_theta(theta, a, tx):
    ones = torch.ones((tx.shape[0], 1), device=tx.device, dtype=tx.dtype)
    aug = torch.cat([tx, ones], dim=1)
    z = aug @ theta.T
    h = torch.relu(z) ** 3
    return h @ a / math.sqrt(theta.shape[0])

# Residual vectors
def interior_residual_vector(theta, a, tx_int):
    u = model_from_theta(theta, a, tx_int)

    grad_u = torch.autograd.grad(
        u, tx_int,
        grad_outputs=torch.ones_like(u),
        create_graph=True,
        retain_graph=True
    )[0]

    u_t = grad_u[:, [0]]
    u_x = grad_u[:, [1]]

    grad_ux = torch.autograd.grad(
        u_x, tx_int,
        grad_outputs=torch.ones_like(u_x),
        create_graph=True,
        retain_graph=True
    )[0]

    u_xx = grad_ux[:, [1]]
    r = (u_t - u_xx - forcing_f(tx_int)).reshape(-1) / math.sqrt(tx_int.shape[0])
    return r

def boundary_residual_vector(theta, a, tx_bc):
    u = model_from_theta(theta, a, tx_bc).reshape(-1)
    g = u_star(tx_bc).reshape(-1)
    return (u - g) / math.sqrt(tx_bc.shape[0])

# Robust ASW weight selection
# CPU float64 + stable PSD surrogate
CPU = torch.device("cpu")
CPU64 = torch.float64

def interior_residual_vector_cpu(theta, a, tx_int):
    u = model_from_theta(theta, a, tx_int)
    grad_u = torch.autograd.grad(
        u, tx_int,
        grad_outputs=torch.ones_like(u),
        create_graph=True,
        retain_graph=True
    )[0]
    u_t = grad_u[:, [0]]
    u_x = grad_u[:, [1]]

    grad_ux = torch.autograd.grad(
        u_x, tx_int,
        grad_outputs=torch.ones_like(u_x),
        create_graph=True,
        retain_graph=True
    )[0]
    u_xx = grad_ux[:, [1]]
    return (u_t - u_xx - forcing_f(tx_int)).reshape(-1) / math.sqrt(tx_int.shape[0])

def boundary_residual_vector_cpu(theta, a, tx_bc):
    u = model_from_theta(theta, a, tx_bc).reshape(-1)
    g = u_star(tx_bc).reshape(-1)
    return (u - g) / math.sqrt(tx_bc.shape[0])

def compute_jacobians_cpu(theta, a, tx_int, tx_bc):
    theta_c = theta.detach().to(device=CPU, dtype=CPU64).requires_grad_(True)
    a_c = a.detach().to(device=CPU, dtype=CPU64)
    tx_int_c = tx_int.detach().to(device=CPU, dtype=CPU64).requires_grad_(True)
    tx_bc_c = tx_bc.detach().to(device=CPU, dtype=CPU64)

    def f_int(th):
        return interior_residual_vector_cpu(th, a_c, tx_int_c)

    def f_bc(th):
        return boundary_residual_vector_cpu(th, a_c, tx_bc_c)

    Js = torch.autograd.functional.jacobian(
        f_int, theta_c, create_graph=False, strict=False, vectorize=False
    )
    Jh = torch.autograd.functional.jacobian(
        f_bc, theta_c, create_graph=False, strict=False, vectorize=False
    )

    Js = Js.reshape(Js.shape[0], -1)
    Jh = Jh.reshape(Jh.shape[0], -1)
    return Js, Jh

def safe_lambda_min_psd(G):
    G = 0.5 * (G + G.T)
    n = G.shape[0]
    ridge = (1e-10 * (torch.trace(G).abs().item() / max(n, 1))) + 1e-12
    G = G + ridge * torch.eye(n, dtype=G.dtype, device=G.device)

    try:
        svals = torch.linalg.svdvals(G)
        return max(float(svals[-1].item() - ridge), 0.0)
    except Exception:
        G_np = G.detach().cpu().numpy()
        svals = np.linalg.svd(G_np, compute_uv=False)
        return max(float(svals[-1] - ridge), 0.0)

def choose_beta_asw_exact(theta, a, tx_int, tx_bc, grid_size=BETA_GRID_SIZE):
    Js, Jh = compute_jacobians_cpu(theta, a, tx_int, tx_bc)

    K_ss = Js @ Js.T
    K_hh = Jh @ Jh.T
    K_sh = Js @ Jh.T
    K_hs = K_sh.T

    best_beta = 0.5
    best_lmin = -1.0

    for beta in np.linspace(0.0, 1.0, grid_size):
        b1 = float(beta)
        b2 = float(1.0 - beta)
        s = math.sqrt(max(b1 * b2, 0.0))

        top = torch.cat([b1 * K_ss, s * K_sh], dim=1)
        bot = torch.cat([s * K_hs, b2 * K_hh], dim=1)
        G = torch.cat([top, bot], dim=0)

        lmin = safe_lambda_min_psd(G)
        if lmin > best_lmin:
            best_lmin = lmin
            best_beta = beta

    return float(best_beta), float(best_lmin)

# Evaluation grid
@torch.no_grad()
def make_eval_grid(nt=201, nx=201):
    t = torch.linspace(0, 1, nt, device=DEVICE, dtype=DTYPE)
    x = torch.linspace(0, 1, nx, device=DEVICE, dtype=DTYPE)
    TT, XX = torch.meshgrid(t, x, indexing="ij")
    return torch.stack([TT.reshape(-1), XX.reshape(-1)], dim=1)

EVAL_GRID = make_eval_grid()

@torch.no_grad()
def relative_l2_error(theta, a):
    pred = model_from_theta(theta, a, EVAL_GRID)
    true = u_star(EVAL_GRID)
    return (torch.norm(pred - true) / (torch.norm(true) + 1e-14)).item()

# One run
def run_single(seed, method="uniform"):
    assert method in ["uniform", "adaptive"]

    gen_device = DEVICE if DEVICE == "cuda" else "cpu"
    data_gen = torch.Generator(device=gen_device)
    data_gen.manual_seed(seed + 12345)

    tx_int = sample_interior(N_INT, gen=data_gen)
    tx_bc = sample_boundary_initial(N_BC, gen=data_gen)
    tx_int_train = tx_int.clone().detach().requires_grad_(True)

    theta, a = init_theta_and_a(M, seed)
    theta = theta.clone().detach().requires_grad_(True)

    history = {
        "step": [],
        "total_loss": [],
        "int_loss": [],
        "bc_loss": [],
        "rel_l2": [],
        "beta": [],
        "lambda_min": [],
    }

    current_beta = 0.5
    current_lmin = np.nan

    for k in range(STEPS + 1):
        if method == "uniform":
            current_beta = 0.5
            current_lmin = np.nan
        else:
            if (k % WEIGHT_UPDATE_EVERY == 0):
                current_beta, current_lmin = choose_beta_asw_exact(
                    theta, a, tx_int_train, tx_bc, grid_size=BETA_GRID_SIZE
                )

        s = interior_residual_vector(theta, a, tx_int_train)
        h = boundary_residual_vector(theta, a, tx_bc)

        int_loss = 0.5 * torch.sum(s**2)
        bc_loss = 0.5 * torch.sum(h**2)
        total_loss = 0.5 * current_beta * torch.sum(s**2) + 0.5 * (1.0 - current_beta) * torch.sum(h**2)

        if (k % LOG_EVERY == 0) or (k == STEPS):
            history["step"].append(k)
            history["total_loss"].append(float(total_loss.item()))
            history["int_loss"].append(float(int_loss.item()))
            history["bc_loss"].append(float(bc_loss.item()))
            history["rel_l2"].append(relative_l2_error(theta.detach(), a))
            history["beta"].append(float(current_beta))
            history["lambda_min"].append(float(current_lmin) if method == "adaptive" else np.nan)

            if k % max(LOG_EVERY, 500) == 0 or k == STEPS:
                print(f"[{method}] seed={seed} step={k:5d} loss={total_loss.item():.3e} beta={current_beta:.3f}")

        if k == STEPS:
            break

        total_loss.backward()
        with torch.no_grad():
            theta -= LR * theta.grad
            theta.grad.zero_()

    return history

