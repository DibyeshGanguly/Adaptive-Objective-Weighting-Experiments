# Aggregation
def stack_metric(histories, key):
    return np.stack([np.array(h[key], dtype=np.float64) for h in histories], axis=0)

def mean_metric(histories, key):
    return stack_metric(histories, key).mean(axis=0)

def positive_limits(*arrays, low_pad=0.92, high_pad=1.08):
    vals = np.concatenate([np.ravel(np.asarray(a, dtype=np.float64)) for a in arrays])
    vals = vals[np.isfinite(vals) & (vals > 0)]
    return vals.min() * low_pad, vals.max() * high_pad

def ema_smooth(y, alpha=0.25):
    y = np.asarray(y, dtype=np.float64)
    out = np.zeros_like(y)
    out[0] = y[0]
    for i in range(1, len(y)):
        out[i] = alpha * y[i] + (1 - alpha) * out[i-1]
    return out

